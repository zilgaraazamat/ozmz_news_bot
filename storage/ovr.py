"""Overall Rating (OVR) — чистая функция от статистики игрока.

OVR никогда не хранится и никогда не редактируется вручную — ни через
админку, ни через какой-либо другой путь. Это единственное место в
приложении, где он считается: вход — текущие games_played/mvp_count/
tournament_wins (см. storage/player_stats.py), выход — рейтинг. Один и тот
же вход всегда даёт один и тот же результат, без обращений к БД и без
побочных эффектов.

Поскольку OVR не хранится, он физически не может «устареть» или разойтись
с реальной статистикой — он автоматически пересчитывается на каждый запрос
из актуальных данных.

Формула (версия 2 — старт с 1, без голов):
    OVR = 1
        + (сыгранных игр // 5)      — +1 за каждые 5 сыгранных игр
        + MVP-наград                — +1 за каждую награду MVP
        + побед в турнирах × 3      — +3 за каждую победу в турнире

Голы в формулу не входят — это отдельная статистика (лидерборд «Лучшие
бомбардиры», достижения), не влияющая на рейтинг.

Чтобы поменять формулу — правится только этот файл, все места, где OVR
показывается (Home, профиль, публичная страница игрока, лидерборд),
продолжат работать без изменений, потому что читают уже готовое число из
get_player_stats().
"""

BASE_OVR = 1
GAMES_PER_POINT = 5
GAMES_POINT_VALUE = 1
MVP_POINT_VALUE = 1
TOURNAMENT_WIN_POINT_VALUE = 3


def calculate_ovr(games_played, mvp_count, tournament_wins=0):
    """Чистая функция: (сыгранные игры, MVP, победы в турнирах) → OVR.
    Отрицательные/некорректные значения не могут утащить рейтинг ниже базы."""
    games_played = max(0, int(games_played or 0))
    mvp_count = max(0, int(mvp_count or 0))
    tournament_wins = max(0, int(tournament_wins or 0))

    return (
        BASE_OVR
        + (games_played // GAMES_PER_POINT) * GAMES_POINT_VALUE
        + mvp_count * MVP_POINT_VALUE
        + tournament_wins * TOURNAMENT_WIN_POINT_VALUE
    )
